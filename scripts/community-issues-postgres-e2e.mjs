import {Pool} from 'pg';
import {randomBytes} from 'node:crypto';
import {mkdirSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {compileProject} from '../dist/compiler.js';
import {startNodeHttpSource} from '../dist/http/node-adapter.js';
import {postgresPoolAdapter} from '../dist/db/postgres.js';
import {issueCapability} from '../dist/runtime/capabilities.js';
import {AuthService} from '../dist/runtime/auth.js';
import {authenticatedSession, rolePolicy} from '../dist/http/auth-policy.js';
import {principalFromRequest} from '../dist/runtime/auth-http.js';

const baseConnection = process.env.BMEC_POSTGRES_URL;
if (!baseConnection) throw new Error('BMEC_POSTGRES_URL is required');
if (process.env.BMEC_POSTGRES_DISPOSABLE !== '1') throw new Error('Set BMEC_POSTGRES_DISPOSABLE=1 only for a verified disposable PostgreSQL target');
const project = compileProject(join(process.cwd(), 'examples', 'community-issues', 'main.bmec'));
if (project.diagnostics.length) throw new Error(`CommunityIssues compile failed: ${project.diagnostics.map(diagnostic => diagnostic.code).join(', ')}`);
const schema = `bmec_issues_${process.pid}_${randomBytes(4).toString('hex')}`;
const scopedUrl = new URL(baseConnection);
scopedUrl.searchParams.set('options', `-c search_path=${schema}`);
const pool = new Pool({connectionString: baseConnection});
const scopedPool = new Pool({connectionString: scopedUrl.toString()});
let schemaCreated = false;
let server;
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const readRows = async (base, path, headers) => {
  const response = await fetch(`${base}${path}`, {headers});
  if (response.status !== 200) {
    const body = await response.text();
    throw new Error(`${path} returned HTTP ${response.status}: ${body}`);
  }
  return response.json();
};
const expectPage = (rows, label, after = undefined) => {
  assert(rows.length <= 50, `${label} exceeded the 50-row bound`);
  assert(rows.every(row => Number(row.repository?.id ?? row.repository) === 1), `${label} returned a foreign repository row`);
  assert(rows.every((row, index) => index === 0 || rows[index - 1].id < row.id), `${label} is not strictly ordered by id`);
  if (after !== undefined) assert(rows.every(row => Number(row.id) > after), `${label} returned a row at/before its cursor`);
};

try {
  const version = (await pool.query('SELECT version() AS version')).rows[0].version;
  await pool.query(`CREATE SCHEMA "${schema}"`);
  schemaCreated = true;
  await scopedPool.query('CREATE TABLE "Repository" ("id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "name" text NOT NULL, "slug" text NOT NULL UNIQUE)');
  await scopedPool.query('CREATE TABLE "Issue" ("id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "repository" bigint NOT NULL REFERENCES "Repository"("id"), "title" text NOT NULL, "description" text NOT NULL, "state" text NOT NULL, "createdBy" text NOT NULL, "createdAt" bigint NOT NULL)');
  await scopedPool.query('CREATE TABLE "IssueComment" ("id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "issue" bigint NOT NULL REFERENCES "Issue"("id"), "body" text NOT NULL, "createdBy" text NOT NULL)');
  await scopedPool.query('INSERT INTO "Repository" ("name", "slug") VALUES ($1, $2), ($3, $4)', ['Compiler', 'compiler', 'Editor', 'editor']);
  await scopedPool.query(`INSERT INTO "Issue" ("repository", "title", "description", "state", "createdBy", "createdAt") SELECT 1, CASE WHEN n <= 73 AND n % 2 = 0 THEN 'needle title ' || n ELSE 'Issue ' || n END, CASE WHEN n <= 73 AND n % 2 = 1 THEN 'needle description ' || n ELSE 'Ordinary description ' || n END, 'Open', 'reporter', 1760000000000 + n FROM generate_series(1, 104) AS n`);
  await scopedPool.query(`INSERT INTO "Issue" ("repository", "title", "description", "state", "createdBy", "createdAt") SELECT 2, 'needle foreign ' || n, 'foreign repository issue', 'Open', 'reporter', 1760000001000 + n FROM generate_series(1, 7) AS n`);

  const auth = new AuthService();
  await auth.register('maintainer', 'maintainer pass', {role: 'maintainer'});
  await auth.register('reporter', 'reporter pass', {role: 'reporter'});
  const maintainerSession = await auth.login('maintainer', 'maintainer pass');
  const reporterSession = await auth.login('reporter', 'reporter pass');
  assert(maintainerSession && reporterSession, 'CommunityIssues sessions could not be created');
  const maintainer = {authorization: `Bearer ${maintainerSession.id}`};
  const reporter = {authorization: `Bearer ${reporterSession.id}`};
  server = await startNodeHttpSource(project.ir, {
    capabilityTokens: new Map([['database', issueCapability('database')], ['time', issueCapability('time')]]),
    database: {adapter: postgresPoolAdapter(scopedPool), schema: project.ir.db},
    configureRouter: router => {
      router.registerPolicy('authenticated', authenticatedSession(auth.sessions));
      router.registerPolicy('role:maintainer', rolePolicy(auth, 'maintainer'));
      router.setPrincipalResolver(request => principalFromRequest(request, auth));
    },
  });

  assert((await fetch(`${server.url}/issues`)).status === 403, 'anonymous issue browsing was not denied');
  const first = await readRows(server.url, '/repositories/by-slug/compiler/issues', reporter);
  const next = await readRows(server.url, `/repositories/by-slug/compiler/issues/pages/${first.at(-1).id}`, reporter);
  const last = await readRows(server.url, `/repositories/by-slug/compiler/issues/pages/${next.at(-1).id}`, reporter);
  expectPage(first, 'repository issues page 1');
  expectPage(next, 'repository issues page 2', Number(first.at(-1).id));
  expectPage(last, 'repository issues page 3', Number(next.at(-1).id));
  assert([first.length, next.length, last.length].join('/') === '50/50/4', 'repository-scoped issue pages expected 50/50/4');
  const allScoped = [...first, ...next, ...last];
  assert(new Set(allScoped.map(issue => issue.id)).size === 104, 'repository cursor pages contained duplicates');
  assert(JSON.stringify(await readRows(server.url, '/repositories/by-slug/missing/issues', reporter)) === '[]', 'unknown repository did not return an empty list');

  const searchFirst = await readRows(server.url, '/repositories/by-slug/compiler/issues/search/needle', reporter);
  const searchNext = await readRows(server.url, `/repositories/by-slug/compiler/issues/search/needle/pages/${searchFirst.at(-1).id}`, reporter);
  const searchEnd = await readRows(server.url, `/repositories/by-slug/compiler/issues/search/needle/pages/${searchNext.at(-1).id}`, reporter);
  expectPage(searchFirst, 'scoped search page 1');
  expectPage(searchNext, 'scoped search continuation', Number(searchFirst.at(-1).id));
  assert([searchFirst.length, searchNext.length, searchEnd.length].join('/') === '50/23/0', 'repository-scoped search expected 50/23/0 rows');
  const searchRows = [...searchFirst, ...searchNext];
  assert(new Set(searchRows.map(issue => issue.id)).size === 73, 'scoped search returned duplicates');
  assert(searchRows.some(issue => issue.title.startsWith('Issue ') && issue.description.startsWith('needle description ')), 'scoped search missed description-only matches');
  assert(searchRows.every(issue => Number(issue.repository?.id ?? issue.repository) === 1), 'scoped search leaked another repository');

  const reporterStatus = await fetch(`${server.url}/issues/1/status`, {method: 'PATCH', headers: {...reporter, 'content-type': 'application/json'}, body: JSON.stringify({state: 'Closed'})});
  assert(reporterStatus.status === 403, `reporter status update returned HTTP ${reporterStatus.status}`);
  const maintainerStatus = await fetch(`${server.url}/issues/1/status`, {method: 'PATCH', headers: {...maintainer, 'content-type': 'application/json'}, body: JSON.stringify({state: 'Closed'})});
  if (maintainerStatus.status !== 200) throw new Error(`maintainer status update returned HTTP ${maintainerStatus.status}: ${await maintainerStatus.text()}`);
  const comment = await fetch(`${server.url}/issues/1/comments`, {method: 'POST', headers: {...reporter, 'content-type': 'application/json'}, body: JSON.stringify({body: 'Reproduced on PostgreSQL'})});
  if (comment.status !== 200) throw new Error(`reporter comment returned HTTP ${comment.status}: ${await comment.text()}`);
  const commentId = Number(await comment.json());
  const comments = await readRows(server.url, '/issues/1/comments', reporter);
  assert(comments.some(item => item.id === commentId && item.body === 'Reproduced on PostgreSQL' && item.createdBy === 'reporter'), 'comment attribution did not use the authenticated reporter');
  const persisted = await scopedPool.query('SELECT "state", "createdBy", "createdAt" FROM "Issue" WHERE "id" = 1');
  assert(persisted.rows[0]?.state === 'Closed' && persisted.rows[0]?.createdBy === 'reporter' && Number(persisted.rows[0]?.createdAt) === 1760000000001, 'maintainer update did not preserve immutable issue attribution/time');

  const evidence = {gate: 'BMEC_COMMUNITY_ISSUES_POSTGRES', recordedAt: new Date().toISOString(), platform: `${process.platform}/${process.arch}`, node: process.version, database: version, schemaIsolation: 'fresh random schema; dropped after run', routes: {repositoryIssues: [first.length, next.length, last.length], repositorySearch: [searchFirst.length, searchNext.length, searchEnd.length], pageLimit: 50, orderedUniqueCursors: true, foreignRowsInScopedList: 0, foreignRowsInScopedSearch: 0, unknownRepository: 'empty list'}, accessControl: {anonymousIssueReadDenied: true, reporterStatusChangeDenied: true, maintainerStatusChangeAccepted: true, reporterCommentAttributedToPrincipal: true, issueCreatorAndTimestampPreserved: true}, limitations: ['Local disposable PostgreSQL only; no hosted/production performance claim', 'Route-level database check only; Chromium browser workflow remains separately verified on SQLite', 'This is a GitHub-like issue tracker demo, not Git/GitHub integration']};
  const evidencePath = process.env.BMEC_COMMUNITY_ISSUES_POSTGRES_EVIDENCE;
  if (evidencePath) { mkdirSync(dirname(evidencePath), {recursive: true}); writeFileSync(evidencePath, `${JSON.stringify(evidence, null, 2)}\n`); }
  console.log(JSON.stringify(evidence, null, 2));
} finally {
  await server?.close();
  await scopedPool.end();
  if (schemaCreated) await pool.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`).catch(() => {});
  await pool.end();
}
