import {Pool} from 'pg';
import {randomBytes} from 'node:crypto';
import {mkdtempSync, mkdirSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname, join} from 'node:path';
import {compileProject} from '../dist/compiler.js';
import {buildRelease} from '../dist/release/release.js';
import {startNodeRelease} from '../dist/release/server.js';
import {postgresPoolAdapter} from '../dist/db/postgres.js';
import {issueCapability} from '../dist/runtime/capabilities.js';
import {AuthService} from '../dist/runtime/auth.js';
import {rolePolicy} from '../dist/http/auth-policy.js';
import {principalFromRequest} from '../dist/runtime/auth-http.js';

const baseConnection = process.env.BMEC_POSTGRES_URL;
if (!baseConnection) throw new Error('BMEC_POSTGRES_URL is required');
if (process.env.BMEC_POSTGRES_DISPOSABLE !== '1') throw new Error('Set BMEC_POSTGRES_DISPOSABLE=1 only for a verified disposable PostgreSQL target');
const project = compileProject(join(process.cwd(), 'examples', 'journal', 'main.bmec'));
if (project.diagnostics.length) throw new Error(`Journal compile failed: ${project.diagnostics.map(diagnostic => diagnostic.code).join(', ')}`);
const schema = `bmec_journal_${process.pid}_${randomBytes(4).toString('hex')}`;
const scopedUrl = new URL(baseConnection);
scopedUrl.searchParams.set('options', `-c search_path=${schema}`);
const pool = new Pool({connectionString: baseConnection});
const scopedPool = new Pool({connectionString: scopedUrl.toString()});
const temp = mkdtempSync(join(tmpdir(), 'bmec-journal-postgres-'));
let schemaCreated = false;
let server;
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const expectPage = (rows, label, after = undefined) => {
  assert(rows.length <= 50, `${label} exceeded the 50-row bound`);
  assert(rows.every(row => row.published === true), `${label} returned an unpublished row`);
  assert(rows.every((row, index) => index === 0 || rows[index - 1].slug < row.slug), `${label} is not strictly slug-ordered`);
  if (after !== undefined) assert(rows.every(row => row.slug > after), `${label} returned a row at/before its cursor`);
};

try {
  const version = (await pool.query('SELECT version() AS version')).rows[0].version;
  await pool.query(`CREATE SCHEMA "${schema}"`);
  schemaCreated = true;
  await scopedPool.query('CREATE TABLE "Post" ("id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "title" text NOT NULL, "slug" text NOT NULL UNIQUE, "summary" text NOT NULL, "body" text NOT NULL, "published" boolean NOT NULL DEFAULT false)');
  await scopedPool.query('INSERT INTO "Post" ("title", "slug", "summary", "body", "published") VALUES ($1, $2, $3, $4, $5)', ['Draft note', 'draft-note', 'Private draft', 'Draft body', false]);
  await scopedPool.query('INSERT INTO "Post" ("title", "slug", "summary", "body", "published") VALUES ($1, $2, $3, $4, $5)', ['Published note', 'published-note', 'Visible article', 'Published body', true]);
  await scopedPool.query(`INSERT INTO "Post" ("title", "slug", "summary", "body", "published") SELECT 'needle journal result ' || n, 'needle-' || lpad((n - 1)::text, 3, '0'), 'Searchable published entry', 'Published search fixture', true FROM generate_series(1, 73) AS n`);
  await scopedPool.query(`INSERT INTO "Post" ("title", "slug", "summary", "body", "published") SELECT 'needle draft ' || n, 'needle-draft-' || n, 'Drafts stay private', 'Unpublished search fixture', false FROM generate_series(1, 7) AS n`);

  const output = join(temp, 'release');
  buildRelease(project.ir, output, {packageName: 'journal', packageVersion: '0.7.0', languageVersion: '0.1'});
  const auth = new AuthService();
  await auth.register('editor', 'editor pass', {role: 'admin'});
  const session = await auth.login('editor', 'editor pass');
  assert(session, 'Journal admin test session could not be created');
  const editor = {authorization: `Bearer ${session.id}`};
  server = await startNodeRelease(output, {
    capabilityTokens: new Map([['database', issueCapability('database')]]),
    database: {adapter: postgresPoolAdapter(scopedPool), schema: project.ir.db},
    configureRouter: router => {
      router.setPrincipalResolver(request => principalFromRequest(request, auth));
      router.registerPolicy('role:admin', rolePolicy(auth, 'admin'));
    },
  });

  assert((await fetch(`${server.url}/posts`)).status === 403, 'admin editor route was exposed anonymously');
  const editorPosts = await (await fetch(`${server.url}/posts`, {headers: editor})).json();
  assert(editorPosts.length === 82, `admin editor list expected 82 rows, got ${editorPosts.length}`);
  assert(editorPosts.some(post => post.slug === 'needle-draft-1' && post.published === false), 'admin editor list did not retain draft rows');

  const first = await (await fetch(`${server.url}/published-posts`)).json();
  const next = await (await fetch(`${server.url}/published-posts/pages/${first.at(-1).slug}`)).json();
  expectPage(first, 'published list page 1');
  expectPage(next, 'published list continuation', first.at(-1).slug);
  assert(first.length === 50 && next.length === 24 && [...first, ...next].length === 74, 'published list expected 74 rows as 50/24');
  assert([...first, ...next].some(post => post.slug === 'published-note'), 'published list omitted its single non-search result');

  const searchFirst = await (await fetch(`${server.url}/published-posts/search/needle`)).json();
  const searchNext = await (await fetch(`${server.url}/published-posts/search/needle/pages/${searchFirst.at(-1).slug}`)).json();
  const searchEnd = await (await fetch(`${server.url}/published-posts/search/needle/pages/${searchNext.at(-1).slug}`)).json();
  expectPage(searchFirst, 'published search page 1');
  expectPage(searchNext, 'published search continuation', searchFirst.at(-1).slug);
  assert([searchFirst.length, searchNext.length, searchEnd.length].join('/') === '50/23/0', 'published search expected 50/23/0 rows');
  const searchSlugs = [...searchFirst, ...searchNext].map(post => post.slug);
  assert(searchSlugs.join(',') === Array.from({length: 73}, (_, index) => `needle-${String(index).padStart(3, '0')}`).join(','), 'published search continuation order or membership was wrong');
  assert(new Set(searchSlugs).size === 73, 'published search continuation returned duplicates');
  assert(JSON.stringify(await (await fetch(`${server.url}/published-posts/search/missing`)).json()) === '[]', 'no-match search did not return an empty list');

  const detail = await (await fetch(`${server.url}/published-posts/published-note`)).json();
  const draftDetail = await (await fetch(`${server.url}/published-posts/draft-note`)).json();
  assert(detail.length === 1 && detail[0].slug === 'published-note' && detail[0].body === 'Published body', 'published dynamic detail did not match exactly one article');
  assert(JSON.stringify(draftDetail) === '[]', 'draft detail was exposed publicly');

  const evidence = {gate: 'BMEC_JOURNAL_POSTGRES', recordedAt: new Date().toISOString(), platform: `${process.platform}/${process.arch}`, node: process.version, database: version, schemaIsolation: 'fresh random schema; dropped after run', totals: {editorPosts: editorPosts.length, published: 74, drafts: 8, titleMatchesIncludingDrafts: 80}, routes: {publishedPages: [first.length, next.length], publishedSearchPages: [searchFirst.length, searchNext.length, searchEnd.length], noMatch: 'empty list', publishedDetail: 'one matching row', draftDetail: 'empty list'}, constraints: {pageSize: 50, orderedUniqueSlugCursor: true, draftExclusion: true, adminEditorDeniedAnonymously: true}, limitations: ['Local disposable PostgreSQL only; no hosted or production performance claim', 'This is route-level coverage, not a full browser/editor workflow or independent editorial review']};
  const evidencePath = process.env.BMEC_JOURNAL_POSTGRES_EVIDENCE;
  if (evidencePath) { mkdirSync(dirname(evidencePath), {recursive: true}); writeFileSync(evidencePath, `${JSON.stringify(evidence, null, 2)}\n`); }
  console.log(JSON.stringify(evidence, null, 2));
} finally {
  await server?.close();
  await scopedPool.end();
  if (schemaCreated) await pool.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`).catch(() => {});
  await pool.end();
  rmSync(temp, {recursive: true, force: true});
}
