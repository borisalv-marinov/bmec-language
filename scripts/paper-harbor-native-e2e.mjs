import {spawn, execFileSync} from 'node:child_process';
import {mkdtempSync, mkdirSync, rmSync, writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {tmpdir} from 'node:os';
import {pathToFileURL} from 'node:url';
import Database from 'better-sqlite3';

const root = process.cwd();
const tempDir = mkdtempSync(join(tmpdir(), 'bmec-paper-harbor-native-'));
const browserTools = join(tempDir, 'browser-tools');
const dataDir = join(tempDir, 'data');
const generatedDir = join(tempDir, 'generated');
const evidenceDir = resolve(process.env.BMEC_EVIDENCE_DIR ?? join(root, 'docs', 'evidence', 'paper-harbor-native'));
mkdirSync(dataDir, {recursive: true});
mkdirSync(evidenceDir, {recursive: true});
execFileSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['install', '--prefix', browserTools, '--no-save', '--ignore-scripts', 'playwright@1.63.0', '@axe-core/playwright@4.10.2'], {stdio: 'inherit', shell: process.platform === 'win32'});
const playwrightModule = await import(pathToFileURL(join(browserTools, 'node_modules', 'playwright', 'index.js')).href);
const {chromium} = playwrightModule.default ?? playwrightModule;
const axeModule = await import(pathToFileURL(join(browserTools, 'node_modules', '@axe-core', 'playwright', 'dist', 'index.mjs')).href);
const {AxeBuilder} = axeModule;
let server;
let browser;
let context;
let page;
let output = '';
let baseUrl;
const observations = {adapter: false, products: 0, productStates: {}, cart: {}, checkout: {}, desktop: {}, tablet: {}, mobile: {}, accessibility: {}, externalRequests: [], browserErrors: []};
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const collect = chunk => { output += chunk.toString(); };
try {
  server = spawn(process.execPath, ['examples/paper-harbor/run.mjs'], {cwd: root, env: {...process.env, BMEC_PORT: '0', BMEC_DATA_DIR: dataDir, BMEC_GENERATED_DIR: generatedDir, BMEC_PAPER_HARBOR_USE_CART_ADAPTER: '0'}, stdio: ['ignore', 'pipe', 'pipe']});
  server.stdout.on('data', collect); server.stderr.on('data', collect);
  const deadline = Date.now() + 20000;
  while (Date.now() < deadline && !baseUrl) {
    baseUrl = output.match(/http:\/\/localhost:\d+/)?.[0];
    if (baseUrl) break;
    if (server.exitCode !== null) throw new Error(`Paper Harbor server exited early: ${output}`);
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  assert(baseUrl, `Paper Harbor server did not start: ${output}`);
  browser = await chromium.launch({headless: true});
  context = await browser.newContext({viewport: {width: 1440, height: 1000}, reducedMotion: 'reduce'});
  page = await context.newPage();
  page.on('request', request => { if (new URL(request.url()).origin !== baseUrl) observations.externalRequests.push(request.url()); });
  page.on('pageerror', error => observations.browserErrors.push(error.message));
  await page.route('**/*', route => new URL(route.request().url()).origin === baseUrl ? route.continue() : route.abort());
  await page.goto(baseUrl, {waitUntil: 'networkidle'});
  const cards = page.locator('[data-pipe-style="ProductCard"]');
  await cards.filter({hasText: 'Field Notes Notebook'}).waitFor();
  observations.products = await cards.count();
  assert(observations.products === 6, `Expected six BMEC-rendered product cards, got ${observations.products}`);
  const productSearch = page.getByLabel('Search products by name or description');
  await productSearch.fill('no matching stationery');
  await page.getByText('No matching items.', {exact: true}).waitFor();
  assert(await cards.filter({hasText: 'Field Notes Notebook'}).count() === 0, 'Product search did not display its empty state');
  await productSearch.fill('');
  await cards.filter({hasText: 'Field Notes Notebook'}).waitFor();
  observations.productStates = {emptySearch: 'PASS', clearSearch: 'PASS'};
  await page.reload({waitUntil: 'networkidle'});
  const axeResults = await new AxeBuilder({page}).analyze();
  const seriousViolations = axeResults.violations.filter(violation => violation.impact === 'serious' || violation.impact === 'critical');
  assert(seriousViolations.length === 0, `Serious/critical axe violations: ${JSON.stringify(seriousViolations)}`);
  observations.accessibility = {serious: 0, critical: 0, moderate: axeResults.violations.filter(violation => violation.impact === 'moderate').length};
  const productList = page.locator('[data-pipe-list="products"]');
  const desktopColumns = await productList.evaluate(element => getComputedStyle(element).gridTemplateColumns.trim().split(/\s+/).length);
  assert(desktopColumns === 3, `Expected a three-column desktop product grid, got ${desktopColumns}`);
  await page.screenshot({path: join(evidenceDir, 'desktop-1440x1000.png'), fullPage: true});
  observations.desktop = await page.evaluate(() => ({width: document.documentElement.scrollWidth, viewport: innerWidth}));
  assert(observations.desktop.width <= observations.desktop.viewport, `Desktop overflow: ${JSON.stringify(observations.desktop)}`);
  await page.setViewportSize({width: 768, height: 900});
  const tabletColumns = await productList.evaluate(element => getComputedStyle(element).gridTemplateColumns.trim().split(/\s+/).length);
  observations.tablet = await page.evaluate(() => ({width: document.documentElement.scrollWidth, viewport: innerWidth, columns: getComputedStyle(document.querySelector('[data-pipe-list="products"]')).gridTemplateColumns.trim().split(/\s+/).length}));
  assert(observations.tablet.width <= observations.tablet.viewport && tabletColumns === 2, `Tablet layout failed: ${JSON.stringify(observations.tablet)}`);
  await page.screenshot({path: join(evidenceDir, 'tablet-768x900.png'), fullPage: true});
  const notebook = cards.filter({hasText: 'Field Notes Notebook'});
  const add = notebook.getByRole('button', {name: 'Add to cart'});
  await add.focus();
  const focusWidth = await add.evaluate(element => getComputedStyle(element).outlineWidth);
  assert(focusWidth === '3px', `Keyboard focus indicator was missing: ${focusWidth}`);
  await page.keyboard.press('Enter');
  await add.click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('bmec-state:PaperHarbor:UI-001:cart') ?? '[]').length === 2);
  const cartList = page.locator('[data-pipe-list="cart"]');
  const expectSubtotal = value => page.waitForFunction(expected => document.querySelector('[data-pipe-style="CartSubtotal"]')?.textContent === expected, value);
  assert(await cartList.getByText('Field Notes Notebook', {exact: true}).count() === 2, 'Native cart did not render both typed rows');
  await expectSubtotal('Subtotal: $24.00');
  await cartList.getByRole('button', {name: 'Add one'}).first().click();
  await page.waitForTimeout(250);
  const quantityProbe = await page.evaluate(() => ({cart: localStorage.getItem('bmec-state:PaperHarbor:UI-001:cart'), button: [...document.querySelectorAll('[data-pipe-list="cart"] button')].find(item => item.textContent === 'Add one')?.dataset.pipeError}));
  assert(JSON.parse(quantityProbe.cart ?? '[]')[0]?.quantity === 2, `Native row increment failed: ${JSON.stringify(quantityProbe)}`);
  await expectSubtotal('Subtotal: $36.00');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('bmec-state:PaperHarbor:UI-001:cart') ?? '[]')[0]?.quantity === 2);
  await cartList.getByRole('button', {name: 'Remove one'}).first().click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('bmec-state:PaperHarbor:UI-001:cart') ?? '[]')[0]?.quantity === 1);
  await expectSubtotal('Subtotal: $24.00');
  await cards.filter({hasText: 'Grid Study Pad'}).getByRole('button', {name: 'Add to cart'}).click();
  await expectSubtotal('Subtotal: $33.50');
  await cartList.getByRole('button', {name: 'Remove item'}).last().click();
  await expectSubtotal('Subtotal: $24.00');
  await page.reload({waitUntil: 'networkidle'});
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('bmec-state:PaperHarbor:UI-001:cart') ?? '[]')[0]?.quantity === 1);
  await expectSubtotal('Subtotal: $24.00');
  observations.cart = {appendProjection: 'PASS', increment: 'PASS', decrement: 'PASS', fractionalMoney: 'PASS ($33.50)', remove: 'PASS', derivedSubtotal: 'PASS', reloadPersistence: 'PASS'};
  await page.getByLabel('Your name').fill('Avery Lin');
  await page.getByLabel('Email address').fill('avery@example.com');
  await page.getByLabel('Delivery address').fill('8 Harbor Lane, Bristol');
  const orderResponses = [];
  page.on('response', response => { if (new URL(response.url()).pathname === '/orders') orderResponses.push(response.status()); });
  await page.getByRole('button', {name: 'Place demo order'}).click();
  await page.getByText('Submitted.', {exact: true}).waitFor();
  assert(orderResponses[0] === 201, `Native checkout expected HTTP 201, received ${JSON.stringify(orderResponses)}`);
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('bmec-state:PaperHarbor:UI-001:cart') ?? '[]').length === 0);
  assert(await cartList.getByText('Field Notes Notebook', {exact: true}).count() === 0, 'Successful checkout did not clear the persisted cart');
  await page.getByRole('button', {name: 'Place demo order'}).click();
  await page.getByText('Add an item to your cart before checkout.', {exact: true}).waitFor();
  assert(orderResponses[1] === 400, `Empty-cart checkout expected HTTP 400, received ${JSON.stringify(orderResponses)}`);
  const databasePath = join(dataDir, 'PaperHarbor.db');
  const database = new Database(databasePath, {readonly: true});
  const order = database.prepare('SELECT * FROM "pipe_Order" ORDER BY id DESC LIMIT 1').get();
  const lines = database.prepare('SELECT * FROM "pipe_OrderLine" WHERE orderId = ?').all(order.id);
  assert(order.email === 'avery@example.com' && lines.length === 2 && lines.reduce((sum, line) => sum + line.quantity, 0) === 2, 'Native checkout did not persist the order and typed cart lines');
  observations.checkout = {response: orderResponses[0], persistedOrder: true, persistedLines: lines.length, cartClearedAfterSuccess: true, emptyCartErrorResponse: orderResponses[1]};
  database.close();
  await page.setViewportSize({width: 360, height: 800});
  observations.mobile = await page.evaluate(() => ({width: document.documentElement.scrollWidth, viewport: innerWidth, cards: [...document.querySelectorAll('[data-pipe-style="ProductCard"]')].filter(card => getComputedStyle(card).display !== 'none').length}));
  assert(observations.mobile.width <= observations.mobile.viewport && observations.mobile.cards === 6, `Mobile layout failed: ${JSON.stringify(observations.mobile)}`);
  await page.screenshot({path: join(evidenceDir, 'mobile-360x800.png'), fullPage: true});
  assert(observations.externalRequests.length === 0, `Unexpected external requests: ${JSON.stringify(observations.externalRequests)}`);
  assert(observations.browserErrors.length === 0, `Browser errors: ${JSON.stringify(observations.browserErrors)}`);
  writeFileSync(join(evidenceDir, 'results.json'), `${JSON.stringify({status: 'PASS', viewportTargets: [{width: 360, height: 800}, {width: 768, height: 900}, {width: 1440, height: 1000}], ...observations}, null, 2)}\n`);
  console.log(`PAPER_HARBOR_NATIVE_E2E PASS — ${JSON.stringify(observations)}`);
} catch (error) {
  console.error(`PAPER_HARBOR_NATIVE_E2E FAIL — ${error.message}`);
  const browserState = await page?.evaluate(() => ({state: globalThis.PIPE_UI_STATE, cart: localStorage.getItem('bmec-state:PaperHarbor:UI-001:cart'), buttons: [...document.querySelectorAll('button')].map(button => ({text: button.textContent, update: button.dataset.pipeStateUpdate, error: button.dataset.pipeError, row: button.closest('[data-pipe-row]')?.dataset.pipeRow}))})).catch(() => null);
  console.error(JSON.stringify({observations, browserState, serverOutput: output}, null, 2));
  process.exitCode = 1;
} finally {
  await browser?.close();
  if (server && server.exitCode === null) { server.kill('SIGTERM'); await new Promise(resolve => server.once('exit', resolve)); }
  rmSync(tempDir, {recursive: true, force: true});
}
